create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Membre' check (char_length(display_name) between 1 and 30),
  created_at timestamptz not null default now()
);

alter table public.profiles
  add column if not exists role text not null default 'user'
    check (role in ('user', 'admin'));
alter table public.profiles
  add column if not exists is_suspended boolean not null default false;

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 500),
  topic text not null default 'Idée' check (char_length(topic) between 1 and 24),
  created_at timestamptz not null default now()
);

create table if not exists public.likes (
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

create index if not exists posts_created_at_idx on public.posts (created_at desc);
create index if not exists posts_user_id_idx on public.posts (user_id);
create index if not exists likes_user_id_idx on public.likes (user_id);

alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.likes enable row level security;

drop policy if exists "Profiles are publicly readable" on public.profiles;
create policy "Profiles are publicly readable" on public.profiles
for select using (true);

drop policy if exists "Users create own profile" on public.profiles;
create policy "Users create own profile" on public.profiles
for insert to authenticated with check (auth.uid() = id);

drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles
for update to authenticated
using (auth.uid() = id and not is_suspended)
with check (auth.uid() = id and not is_suspended);

drop policy if exists "Posts are publicly readable" on public.posts;
create policy "Posts are publicly readable" on public.posts
for select using (true);

drop policy if exists "Authenticated users create own posts" on public.posts;
create policy "Authenticated users create own posts" on public.posts
for insert to authenticated with check (
  auth.uid() = user_id and exists (
    select 1 from public.profiles
    where id = auth.uid() and not is_suspended
  )
);

drop policy if exists "Users delete own posts" on public.posts;
create policy "Users delete own posts" on public.posts
for delete to authenticated using (
  auth.uid() = user_id and exists (
    select 1 from public.profiles
    where id = auth.uid() and not is_suspended
  )
);

drop policy if exists "Likes are publicly readable" on public.likes;

drop policy if exists "Users like as themselves" on public.likes;
create policy "Users like as themselves" on public.likes
for insert to authenticated with check (
  auth.uid() = user_id and exists (
    select 1 from public.profiles
    where id = auth.uid() and not is_suspended
  )
);

drop policy if exists "Users remove own likes" on public.likes;
create policy "Users remove own likes" on public.likes
for delete to authenticated using (
  auth.uid() = user_id and exists (
    select 1 from public.profiles
    where id = auth.uid() and not is_suspended
  )
);

create or replace function public.get_post_engagement(post_ids bigint[])
returns table (post_id bigint, likes_count bigint, liked boolean)
language sql
stable
security definer
set search_path = ''
as $$
  select likes.post_id, count(*),
    coalesce(bool_or(likes.user_id = auth.uid()), false)
  from public.likes as likes
  where likes.post_id = any(coalesce(post_ids, array[]::bigint[]))
  group by likes.post_id;
$$;

-- Créer automatiquement un profil lorsqu'un utilisateur s'inscrit.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(nullif(left(new.raw_user_meta_data ->> 'display_name', 30), ''), 'Membre')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.get_my_access()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'role', coalesce(profiles.role, 'user'),
    'is_suspended', coalesce(profiles.is_suspended, false)
  )
  from (select auth.uid() as id) as caller
  left join public.profiles on profiles.id = caller.id;
$$;

drop function if exists public.admin_list_users();
create function public.admin_list_users(
  result_limit integer default 50,
  result_offset integer default 0
)
returns table (
  user_id uuid,
  email text,
  display_name text,
  created_at timestamptz,
  role text,
  is_suspended boolean,
  total_count bigint
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.profiles as admin_profile
    where admin_profile.id = auth.uid()
      and admin_profile.role = 'admin'
      and not admin_profile.is_suspended
  ) then
    raise exception 'Accès administrateur requis';
  end if;

  return query
  select users.id, users.email::text,
    coalesce(profiles.display_name, 'Membre'), users.created_at,
    coalesce(profiles.role, 'user'), coalesce(profiles.is_suspended, false),
    count(*) over ()
  from auth.users as users
  left join public.profiles on profiles.id = users.id
  order by users.created_at desc
  limit least(greatest(coalesce(result_limit, 50), 1), 100)
  offset greatest(coalesce(result_offset, 0), 0);
end;
$$;

create or replace function public.admin_update_user(
  target_user_id uuid,
  target_role text,
  target_is_suspended boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  old_role text;
  old_is_suspended boolean;
begin
  if not exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin' and not is_suspended
  ) then
    raise exception 'Accès administrateur requis';
  end if;
  if target_user_id = auth.uid() then
    raise exception 'Tu ne peux pas modifier ton propre compte ici';
  end if;
  if target_role is null or target_role not in ('user', 'admin')
    or target_is_suspended is null then
    raise exception 'Valeurs de compte invalides';
  end if;

  perform 1 from public.profiles as profiles
  where profiles.role = 'admin' and not profiles.is_suspended
  order by profiles.id
  for update;

  select role, is_suspended into old_role, old_is_suspended
  from public.profiles where id = target_user_id;
  if not found then
    raise exception 'Compte introuvable';
  end if;
  if old_role = 'admin' and not old_is_suspended
    and (target_role <> 'admin' or target_is_suspended)
    and (select count(*) from public.profiles
      where role = 'admin' and not is_suspended) <= 1 then
    raise exception 'Impossible de désactiver le dernier administrateur';
  end if;

  update public.profiles
  set role = target_role, is_suspended = target_is_suspended
  where id = target_user_id;
end;
$$;

create or replace function public.admin_delete_user(target_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_role text;
  target_is_suspended boolean;
begin
  if not exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin' and not is_suspended
  ) then
    raise exception 'Accès administrateur requis';
  end if;
  if target_user_id = auth.uid() then
    raise exception 'Tu ne peux pas supprimer ton propre compte ici';
  end if;

  perform 1 from public.profiles as profiles
  where profiles.role = 'admin' and not profiles.is_suspended
  order by profiles.id
  for update;

  select role, is_suspended into target_role, target_is_suspended
  from public.profiles where id = target_user_id;
  if not found then
    raise exception 'Compte introuvable';
  end if;
  if target_role = 'admin' and not target_is_suspended
    and (select count(*) from public.profiles
      where role = 'admin' and not is_suspended) <= 1 then
    raise exception 'Impossible de supprimer le dernier administrateur';
  end if;

  delete from auth.users where id = target_user_id;
end;
$$;

